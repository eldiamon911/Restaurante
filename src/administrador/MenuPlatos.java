    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String nombre = txtNombre.getText();
        String precio = txtPrecio.getText();
        String descrip = txtDescripcion.getText();

        if (nombre.isEmpty() || precio.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llene nombre y precio");
            return;
        }
        if (cboCategoria.getSelectedIndex() < 0) {
            JOptionPane.showMessageDialog(this, "Primero cree una categoria");
            return;
        }

        int idCat = idsCategoria.get(cboCategoria.getSelectedIndex());
        String sql = "INSERT INTO platos (id_categoria, nombre, descrip, precio) VALUES (?, ?, ?, ?)";

        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setInt(1, idCat);
            st.setString(2, nombre);
            st.setString(3, descrip);
            st.setDouble(4, Double.parseDouble(precio));
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Plato agregado correctamente");
            cargarPlatos();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al agregar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (idPlatoSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un plato de la tabla");
            return;
        }
        String nombre = txtNombre.getText();
        String precio = txtPrecio.getText();
        String descrip = txtDescripcion.getText();

        if (nombre.isEmpty() || precio.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llene nombre y precio");
            return;
        }
        if (cboCategoria.getSelectedIndex() < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una categoria");
            return;
        }

        int idCat = idsCategoria.get(cboCategoria.getSelectedIndex());
        String sql = "UPDATE platos SET id_categoria=?, nombre=?, descrip=?, precio=? WHERE id_plato=?";

        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setInt(1, idCat);
            st.setString(2, nombre);
            st.setString(3, descrip);
            st.setDouble(4, Double.parseDouble(precio));
            st.setInt(5, idPlatoSeleccionado);
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Plato actualizado correctamente");
            cargarPlatos();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al editar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idPlatoSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un plato de la tabla");
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(this, "¿Eliminar plato?", "Confirmar",
                JOptionPane.YES_NO_OPTION);
        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            Connection con = Conexion.conectar();

            PreparedStatement stReceta = con.prepareStatement(
                    "DELETE FROM receta_ingredientes WHERE id_plato=?");
            stReceta.setInt(1, idPlatoSeleccionado);
            stReceta.executeUpdate();

            PreparedStatement st = con.prepareStatement(
                    "DELETE FROM platos WHERE id_plato=?");
            st.setInt(1, idPlatoSeleccionado);
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Plato eliminado");
            cargarPlatos();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "No se pudo eliminar (puede estar en pedidos): " + e.getMessage());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnNuevaCategoriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevaCategoriaActionPerformed
        String nombre = JOptionPane.showInputDialog(this, "Nombre de la nueva categoria:");
        if (nombre == null || nombre.trim().isEmpty()) {
            return;
        }
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(
                    "INSERT INTO categorias (nombre) VALUES (?)");
            st.setString(1, nombre.trim());
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Categoria creada");
            cargarCategorias();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al crear categoria: " + e.getMessage());
        }
    }//GEN-LAST:event_btnNuevaCategoriaActionPerformed

    private void tblPlatoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPlatoMouseClicked
        int fila = tblPlato.getSelectedRow();
        if (fila >= 0) {
            idPlatoSeleccionado = Integer.parseInt(tblPlato.getValueAt(fila, 0).toString());
            txtNombre.setText(tblPlato.getValueAt(fila, 1).toString());
            String cat = tblPlato.getValueAt(fila, 2).toString();
            txtPrecio.setText(tblPlato.getValueAt(fila, 3).toString());
            txtDescripcion.setText(tblPlato.getValueAt(fila, 4).toString());

            for (int i = 0; i < cboCategoria.getItemCount(); i++) {
                if (cboCategoria.getItemAt(i).equals(cat)) {
                    cboCategoria.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tblPlatoMouseClicked

