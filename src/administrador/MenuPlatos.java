    private void cargarCategorias() {
        cboCategoria.removeAllItems();
        idsCategoria.clear();
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(
                    "SELECT id_categoria, nombre FROM categorias ORDER BY nombre");
            ResultSet rs = st.executeQuery();
            while (rs.next()) {
                idsCategoria.add(rs.getInt("id_categoria"));
                cboCategoria.addItem(rs.getString("nombre"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar categorias: " + e.getMessage());
        }
    }
    
    private void cargarPlatos() {
        DefaultTableModel modelo = (DefaultTableModel) tblPlato.getModel();
        modelo.setRowCount(0);
        String sql = "SELECT p.id_plato, p.nombre, c.nombre AS categoria, p.precio, p.descrip "
                + "FROM platos p JOIN categorias c ON p.id_categoria = c.id_categoria "
                + "ORDER BY p.id_plato";
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            ResultSet rs = st.executeQuery();
            while (rs.next()) {
                Object[] fila = {
                    rs.getInt(1),
                    rs.getString(2),
                    rs.getString(3),
                    rs.getDouble(4),
                    rs.getString(5)
                };
                modelo.addRow(fila);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar platos: " + e.getMessage());
        }
    }
    
