    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String nombre = txtNombre.getText();
        String usuario = txtUsuario.getText();
        String contra = new String(txtContra.getPassword());

        if (nombre.isEmpty() || usuario.isEmpty() || contra.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llene nombre, usuario y contraseña");
            return;
        }

        String rol = cboRol.getSelectedItem().toString();
        String sql = "INSERT INTO usuarios (nombre, usuario, contra, rol) VALUES (?, ?, ?, ?)";
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setString(1, nombre);
            st.setString(2, usuario);
            st.setString(3, contra);
            st.setString(4, rol);
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Usuario agregado correctamente");
            cargarUsuarios();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al agregar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (idUsuarioSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla");
            return;
        }
        String nombre = txtNombre.getText();
        String usuario = txtUsuario.getText();
        String contra = new String(txtContra.getPassword());

        if (nombre.isEmpty() || usuario.isEmpty() || contra.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llene nombre, usuario y contraseña");
            return;
        }

        String rol = cboRol.getSelectedItem().toString();
        String sql = "UPDATE usuarios SET nombre=?, usuario=?, contra=?, rol=? WHERE id_usuario=?";
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setString(1, nombre);
            st.setString(2, usuario);
            st.setString(3, contra);
            st.setString(4, rol);
            st.setInt(5, idUsuarioSeleccionado);
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente");
            cargarUsuarios();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al editar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idUsuarioSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla");
            return;
        }
        if (idUsuarioSeleccionado == login.Sesion.idUsuario) {
            JOptionPane.showMessageDialog(this, "No puede eliminar el usuario con el que inicio sesion");
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(this, "¿Eliminar usuario?", "Confirmar",
                JOptionPane.YES_NO_OPTION);
        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement("DELETE FROM usuarios WHERE id_usuario=?");
            st.setInt(1, idUsuarioSeleccionado);
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Usuario eliminado");
            cargarUsuarios();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "No se pudo eliminar (puede tener pedidos o pagos): " + e.getMessage());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        int fila = tblUsuarios.getSelectedRow();
        if (fila >= 0) {
            idUsuarioSeleccionado = Integer.parseInt(tblUsuarios.getValueAt(fila, 0).toString());
            txtNombre.setText(tblUsuarios.getValueAt(fila, 1).toString());
            txtUsuario.setText(tblUsuarios.getValueAt(fila, 2).toString());
            String rol = tblUsuarios.getValueAt(fila, 3).toString();
            cboRol.setSelectedItem(rol);
        }
    }//GEN-LAST:event_tblUsuariosMouseClicked

