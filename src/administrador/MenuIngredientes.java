    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        String nom = txtNombre.getText();
        String can = txtCantidad.getText();
        String uni = txtUnidad.getText();
        String min = txtMin.getText();
        
        if(nom.isEmpty() || can.isEmpty() ||
        uni.isEmpty() || min.isEmpty() ){
            JOptionPane.showMessageDialog(this,
                   "LLENE TODOS LOS CAMPOS REQUEERIDOS" );
            return;
        }
         String sql = "INSERT INTO ingredientes " +
                 "(nombre, cantidadA, unidad_medida, cantidadM) " +
                 "VALUES (?, ?, ?, ?)";
         
         try{
             Connection con = Conexion.conectar();
             PreparedStatement st = con.prepareStatement(sql);
                st.setString(1, nom);
                st.setDouble(2, Double.parseDouble(can));
                st.setString(3, uni);
                st.setDouble(4, Double.parseDouble(min));
                
                st.executeUpdate();
                
                JOptionPane.showMessageDialog(this,
                "Ingrediente agregado correctamente");

                cargarIngredientes();
                limpiarCampos();

            } catch (Exception e) {

                JOptionPane.showMessageDialog(this,
                "Error al agregar ingrediente: " + e.getMessage());
            }
         
        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void tblIngredienteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblIngredienteMouseClicked
        // TODO add your handling code here:
                                                  
        int fila = tblIngrediente.getSelectedRow();

        if (fila >= 0) {
            // La columna 0 es el ID, empezamos desde la columna 1 (NOMBRE)
            txtNombre.setText(tblIngrediente.getValueAt(fila, 1).toString());
            txtCantidad.setText(tblIngrediente.getValueAt(fila, 2).toString());
            txtUnidad.setText(tblIngrediente.getValueAt(fila, 3).toString());
            txtMin.setText(tblIngrediente.getValueAt(fila, 4).toString());
            idIngredienteSeleccionado = Integer.parseInt(
                    tblIngrediente.getValueAt(fila, 0).toString());
        }
    }//GEN-LAST:event_tblIngredienteMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if(idIngredienteSeleccionado == 0){
            JOptionPane.showMessageDialog(this, "Seleccione un ingrediente de la tabla");
            return;
        }
        
        String nombre = txtNombre.getText();
        String cantidad = txtCantidad.getText();
        String unidad = txtUnidad.getText();
        String min = txtMin.getText();
        
        if(nombre.isEmpty() || cantidad.isEmpty() || unidad.isEmpty() || min.isEmpty()){
            JOptionPane.showMessageDialog(this,"Llen todo los campos requeridos");
            return;
        }
        
        String sql = "UPDATE ingredientes SET nombre=?, cantidadA=?, unidad_medida=?, cantidadM=? WHERE id_ingrediente=?";
        
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            
            st.setString(1, nombre);
            st.setDouble(2, Double.parseDouble(cantidad));
            st.setString(3, unidad);
            st.setDouble(4, Double.parseDouble(min));
            st.setInt(5, idIngredienteSeleccionado);
            st.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Ingrediente actualizado correctamente");
            cargarIngredientes();
            limpiarCampos();
            idIngredienteSeleccionado = 0;
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al editar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if(idIngredienteSeleccionado == 0){
            JOptionPane.showMessageDialog(this, "Seleccione un ingrediente de la tabla");
            return;
        }
        
        int confirmar = JOptionPane.showConfirmDialog(this, "¿Eliminar ingrediente?", "Confirmar",
                JOptionPane.YES_NO_OPTION);
        if(confirmar != JOptionPane.YES_OPTION){
            return;
        }
        
        try {
            Connection conexion = Conexion.conectar();
            
            PreparedStatement stReceta = conexion.prepareStatement(
                    "DELETE FROM receta_ingredientes WHERE id_ingrediente=?");
            stReceta.setInt(1, idIngredienteSeleccionado);
            stReceta.executeUpdate();
            
            PreparedStatement st = conexion.prepareStatement(
                    "DELETE FROM ingredientes WHERE id_ingrediente=?");
            st.setInt(1, idIngredienteSeleccionado);
            st.executeUpdate();
            
            JOptionPane.showMessageDialog(this, "Ingrediente eliminado");
            cargarIngredientes();
            limpiarCampos();
            idIngredienteSeleccionado = 0;
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }   
    }//GEN-LAST:event_btnEliminarActionPerformed

