    private void cargarIngredientes() {
    // Usamos tblIngrediente que es la variable real de tu JTable
    DefaultTableModel modelo = (DefaultTableModel) tblIngrediente.getModel();
    modelo.setRowCount(0);

    String sql = "SELECT * FROM ingredientes";

    try {
        Connection con = Conexion.conectar();
        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            // Mapeamos las columnas con los nombres exactos de tu base de datos
            Object[] fila = {
                rs.getInt("id_ingrediente"),
                rs.getString("nombre"),
                rs.getDouble("cantidadA"),
                rs.getString("unidad_medida"),
                rs.getDouble("cantidadM")
            };

            modelo.addRow(fila);
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error al cargar ingredientes: " + e.getMessage());
    }
}
