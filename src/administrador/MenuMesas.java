    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String numero = txtNumero.getText();
        String capacidad = txtCapacidad.getText();

        if (numero.isEmpty() || capacidad.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llene numero y capacidad");
            return;
        }

        String sql = "INSERT INTO mesas (numero_mesa, capacidad) VALUES (?, ?)";
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setInt(1, Integer.parseInt(numero));
            st.setInt(2, Integer.parseInt(capacidad));
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Mesa agregada correctamente");
            cargarMesas();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al agregar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (idMesaSeleccionada == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una mesa de la tabla");
            return;
        }
        String numero = txtNumero.getText();
        String capacidad = txtCapacidad.getText();

        if (numero.isEmpty() || capacidad.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Llene numero y capacidad");
            return;
        }

        String sql = "UPDATE mesas SET numero_mesa=?, capacidad=? WHERE id_mesa=?";
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setInt(1, Integer.parseInt(numero));
            st.setInt(2, Integer.parseInt(capacidad));
            st.setInt(3, idMesaSeleccionada);
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Mesa actualizada correctamente");
            cargarMesas();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al editar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idMesaSeleccionada == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione una mesa de la tabla");
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(this, "¿Eliminar mesa?", "Confirmar",
                JOptionPane.YES_NO_OPTION);
        if (confirmar != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM mesas WHERE id_mesa=?";
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setInt(1, idMesaSeleccionada);
            st.executeUpdate();

            JOptionPane.showMessageDialog(this, "Mesa eliminada");
            cargarMesas();
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "No se pudo eliminar (puede tener pedidos): " + e.getMessage());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblMesaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMesaMouseClicked
        int fila = tblMesa.getSelectedRow();
        if (fila >= 0) {
            idMesaSeleccionada = Integer.parseInt(tblMesa.getValueAt(fila, 0).toString());
            txtNumero.setText(tblMesa.getValueAt(fila, 1).toString());
            txtCapacidad.setText(tblMesa.getValueAt(fila, 2).toString());
        }
    }//GEN-LAST:event_tblMesaMouseClicked

