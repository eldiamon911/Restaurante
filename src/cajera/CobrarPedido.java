    private void btnPagarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPagarActionPerformed
        if (idPedidoSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un pedido de la tabla");
            return;
        }
        String valor = txtValor.getText().trim();
        if (valor.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escriba el valor pagado");
            return;
        }

        double valorPagado;
        try {
            valorPagado = Double.parseDouble(valor);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "El valor debe ser un numero valido");
            return;
        }

        double totalPedido = 0;
        int fila = tblPedidos.getSelectedRow();
        if (fila >= 0) {
            totalPedido = totalesPedido.get(fila);
        }

        if (valorPagado < totalPedido) {
            JOptionPane.showMessageDialog(this, "El valor pagado es menor al total del pedido ($" + totalPedido + ")");
            return;
        }

        String metodo = cboMetodo.getSelectedItem().toString();
        if (metodo.equals("EFECTIVO")) {
            double cambio = valorPagado - totalPedido;
            JOptionPane.showMessageDialog(this, "Pago correcto. Su cambio/vuelto es: $" + String.format("%.2f", cambio));
        }

        Connection con = null;
        try {
            con = Conexion.conectar();
            con.setAutoCommit(false);

            PreparedStatement stPago = con.prepareStatement(
                    "INSERT INTO pagos (id_pedido, id_cajera, metodo_pago, valor_pagado) "
                    + "VALUES (?, ?, ?, ?)");
            stPago.setInt(1, idPedidoSeleccionado);
            stPago.setInt(2, login.Sesion.idUsuario);
            stPago.setString(3, metodo);
            stPago.setDouble(4, valorPagado);
            stPago.executeUpdate();

            PreparedStatement stPed = con.prepareStatement(
                    "UPDATE pedidos SET estado = 'PAGADO' WHERE id_pedido = ?");
            stPed.setInt(1, idPedidoSeleccionado);
            stPed.executeUpdate();

            PreparedStatement stMesa = con.prepareStatement(
                    "UPDATE mesas SET estado = 'DISPONIBLE' WHERE id_mesa = (SELECT id_mesa FROM pedidos WHERE id_pedido = ?)");
            stMesa.setInt(1, idPedidoSeleccionado);
            stMesa.executeUpdate();

            con.commit();

            JOptionPane.showMessageDialog(this, "¡Pago registrado correctamente y mesa liberada!");
            cargarPedidos();

        } catch (Exception e) {
            try {
                if (con != null) con.rollback();
            } catch (Exception ex) {
                ex.printStackTrace();
            }
            JOptionPane.showMessageDialog(this, "Error al registrar el pago: " + e.getMessage());
        } finally {
            try {
                if (con != null) {
                    con.setAutoCommit(true);
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }
    }//GEN-LAST:event_btnPagarActionPerformed

