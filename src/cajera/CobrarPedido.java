    private void cargarPedidos() {
        idsPedido.clear();
        totalesPedido.clear();
        idPedidoSeleccionado = 0;
        txtValor.setText("");
        
        DefaultTableModel modelo = (DefaultTableModel) tblPedidos.getModel();
        modelo.setRowCount(0);
        
        String sql = "SELECT p.id_pedido, m.numero_mesa, p.fecha, p.total "
                + "FROM pedidos p JOIN mesas m ON p.id_mesa = m.id_mesa "
                + "WHERE p.estado <> 'PAGADO' AND p.estado <> 'CANCELADO' "
                + "ORDER BY p.fecha";
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            ResultSet rs = st.executeQuery();
            while (rs.next()) {
                idsPedido.add(rs.getInt("id_pedido"));
                totalesPedido.add(rs.getDouble("total"));
                Object[] fila = {
                    rs.getInt("id_pedido"),
                    rs.getInt("numero_mesa"),
                    rs.getString("fecha"),
                    rs.getDouble("total")
                };
                modelo.addRow(fila);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar pedidos: " + e.getMessage());
        }
    }

