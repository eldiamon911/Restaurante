    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (lineas.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay platos en la lista para eliminar.");
            return;
        }
        
        Object[] opciones = {"Eliminar seleccionados", "Eliminar todos ", "Cancelar"};
        int seleccion = JOptionPane.showOptionDialog(
                this,
                "¿Qué acción deseas realizar?",
                "Opciones de Eliminación",
                JOptionPane.YES_NO_CANCEL_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                opciones,
                opciones[0]
        );
        
        if (seleccion == 0) {
            int filaSeleccionada = tblDetalle.getSelectedRow();
            if (filaSeleccionada < 0) {
                JOptionPane.showMessageDialog(this, "por favor, selecciona un plato de la tabla.");
                return;
            }
            
            DefaultTableModel modelo = (DefaultTableModel) tblDetalle.getModel();
            modelo.removeRow(filaSeleccionada);
            lineas.remove(filaSeleccionada);
        } else if (seleccion == 1) {
            int confirmar = JOptionPane.showConfirmDialog(
                    this, 
                    "¿Estas seguro de vaciar toda la lista del pedido?",
                    "Confirmar limpieza",
                    JOptionPane.YES_NO_OPTION
            );
            
            if (confirmar == JOptionPane.YES_OPTION) {
                lineas.clear();
                DefaultTableModel modelo = (DefaultTableModel) tblDetalle.getModel();
                modelo.setRowCount(0);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

