    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed

        if (cboPlato.getSelectedIndex() < 0) {
            JOptionPane.showMessageDialog(this, "No hay platos. Cree platos primero.");
            return;
        }
        String cant = txtCantidad.getText();
        if (cant.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escriba la cantidad");
            return;
        }
        int cantidad;
        try {
            cantidad = Integer.parseInt(cant);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser un numero");
            return;
        }
        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this, "La cantidad debe ser mayor a cero");
            return;
        }

        int idx = cboPlato.getSelectedIndex();
        int idPlatoActual = idsPlato.get(idx);

        try {
            Connection con = Conexion.conectar();
            PreparedStatement stCheck = con.prepareStatement("SELECT stock, nombre FROM platos WHERE id_plato = ?");
            stCheck.setInt(1, idPlatoActual);
            ResultSet rsCheck = stCheck.executeQuery();
            if (rsCheck.next()) {
                int stockActual = rsCheck.getInt("stock");
                if (stockActual < cantidad) {
                    JOptionPane.showMessageDialog(this, 
                        "Stock insuficiente para el plato: " + rsCheck.getString("nombre") + 
                        "\n(Disponible en inventario: " + stockActual + ")");
                    con.close();
                    return; // Detiene la acción y no lo deja agregar a la tabla
                }
            }
            con.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al verificar stock: " + e.getMessage());
            return;
        }

        double precio = preciosPlato.get(idx);
        double subtotal = precio * cantidad;
        String observacion = txtObservaciones.getText().trim();

        Linea l = new Linea();
        l.idPlato = idPlatoActual;
        l.cantidad = cantidad;
        l.precio = precio;
        l.subtotal = subtotal;
        l.observacio = observacion;
        lineas.add(l);

        DefaultTableModel modelo = (DefaultTableModel) tblDetalle.getModel();
        modelo.addRow(new Object[]{ cboPlato.getSelectedItem(), cantidad, precio, subtotal, observacion});

        txtCantidad.setText("");
        txtObservaciones.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (cboMesa.getSelectedIndex() < 0) {
            JOptionPane.showMessageDialog(this, "No hay mesas. Cree mesas primero.");
            return;
        }
        if (lineas.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Agregue al menos un plato a la lista");
            return;
        }

        int idMesa = idsMesa.get(cboMesa.getSelectedIndex());
        double total = 0;
        for (Linea l : lineas) {
            total = total + l.subtotal;
        }

        Connection con = null;
        try {
            con = Conexion.conectar();
            con.setAutoCommit(false);

            for (Linea l : lineas) {
                PreparedStatement stCheck = con.prepareStatement("SELECT stock, nombre FROM platos WHERE id_plato = ?");
                stCheck.setInt(1, l.idPlato);
                ResultSet rsCheck = stCheck.executeQuery();
                if (rsCheck.next()) {
                    int stockActual = rsCheck.getInt("stock");
                    String nombrePlato = rsCheck.getString("nombre");
                    if (stockActual < l.cantidad) {
                        JOptionPane.showMessageDialog(this, "Stock insuficiente para el plato: " + nombrePlato + " (Disponible: " + stockActual + ")");
                        con.rollback();
                        return;
                    }
                }
            }

            PreparedStatement st = con.prepareStatement(
                    "INSERT INTO pedidos (id_mesa, id_mesera, fecha, estado, total) "
                    + "VALUES (?, ?, NOW(), 'CONFIRMADO', ?)",
                    Statement.RETURN_GENERATED_KEYS);
            st.setInt(1, idMesa);
            st.setInt(2, login.Sesion.idUsuario);
            st.setDouble(3, total);
            st.executeUpdate();

            ResultSet keys = st.getGeneratedKeys();
            int idPedido = 0;
            if (keys.next()) {
                idPedido = keys.getInt(1);
            }

            PreparedStatement stDet = con.prepareStatement(
                    "INSERT INTO detalle_pedido (id_pedido, id_plato, cantidad, precio_unitario, subtotal, observacion) "
                    + "VALUES (?, ?, ?, ?, ?, ?)");
            
            PreparedStatement stStock = con.prepareStatement(
                    "UPDATE platos SET stock = stock - ? WHERE id_plato = ?");

            for (Linea l : lineas) {
                stDet.setInt(1, idPedido);
                stDet.setInt(2, l.idPlato);
                stDet.setInt(3, l.cantidad);
                stDet.setDouble(4, l.precio);
                stDet.setDouble(5, l.subtotal);
                stDet.setString(6, l.observacio);
                stDet.executeUpdate();

                // Descontar stock
                stStock.setInt(1, l.cantidad);
                stStock.setInt(2, l.idPlato);
                stStock.executeUpdate();
            }

            con.commit();

            JOptionPane.showMessageDialog(this, "Pedido guardado y stock actualizado. Total: " + total);

            lineas.clear();
            ((DefaultTableModel) tblDetalle.getModel()).setRowCount(0);
            cargarPlatos();

        } catch (Exception e) {
            try {
                if (con != null) con.rollback();
            } catch (Exception ex) {
                logger.log(java.util.logging.Level.SEVERE, null, ex);
            }
            JOptionPane.showMessageDialog(this, "Error al guardar el pedido: " + e.getMessage());
        } finally {
            try {
                if (con != null) con.close();
            } catch (Exception ex) {
                logger.log(java.util.logging.Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

