    private void cargarMesas() {
        cboMesa.removeAllItems();
        idsMesa.clear();
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(
                    "SELECT id_mesa, numero_mesa FROM mesas ORDER BY numero_mesa");
            ResultSet rs = st.executeQuery();
            while (rs.next()) {
                idsMesa.add(rs.getInt(1));
                cboMesa.addItem("Mesa " + rs.getInt(2));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar mesas: " + e.getMessage());
        }
    }
    
    private void cargarPlatos() {
        cboPlato.removeAllItems();
        idsPlato.clear();
        preciosPlato.clear();
        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(
                    "SELECT id_plato, nombre, precio FROM platos WHERE disponible = TRUE ORDER BY nombre");
            ResultSet rs = st.executeQuery();
            while (rs.next()) {
                idsPlato.add(rs.getInt("id_plato"));
                preciosPlato.add(rs.getDouble("precio"));
                cboPlato.addItem(rs.getString("nombre"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar platos: " + e.getMessage());
        }
    }

