    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        // TODO add your handling code here:
        String usu = txtUsuario.getText();
        String con = new String(txtpass.getPassword());
        
        try{
            Connection con1 = Conexion.conectar();
        
            PreparedStatement pst = con1.prepareStatement(
            "SELECT * FROM usuarios WHERE usuario = ? AND contra = ?");
                pst.setString(1,usu);
                pst.setString(2,con);
                ResultSet rs = pst.executeQuery();
                
                if(rs.next()){
                   String ro = rs.getString("rol");
                   JOptionPane.showMessageDialog(this,"BIENVENIDO  "
                   + usu);
                   
                   login.Sesion.idUsuario = rs.getInt("id_usuario");
                   login.Sesion.usuario = usu;
                   login.Sesion.rol = ro;
                   
                   if(ro.equalsIgnoreCase("admin")){
                       MenuAdministrador admin = new MenuAdministrador();
                       admin.setVisible(true);
                       this.dispose();
                   } else if (ro.equalsIgnoreCase("cajera")){
                       MenuCajera mes = new MenuCajera();
                       mes.setVisible(true);
                       this.dispose();
                       
                   } else if (ro.equalsIgnoreCase("mesera")){
                       mesera.MenuMesera mm = new mesera.MenuMesera();
                       mm.setVisible(true);
                       this.dispose();
                   }
                   
                }else{
                       JOptionPane.showMessageDialog(this,
                               "Usuario o contraseña incorrecto");
                   }
        }catch (SQLException e){
            JOptionPane.showMessageDialog(this, "Error base datos:"
            + e.getMessage());
        }
        
        
                
                

        
            
                
    }//GEN-LAST:event_btnIngresarActionPerformed

