    private void cargarInventario() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("Ingrediente");
        modelo.addColumn("Cantidad actual");
        modelo.addColumn("Cantidad minima");
        modelo.addColumn("Unidad");
        modelo.addColumn("Estado");
        tblInventario.setModel(modelo);

        String sql = "SELECT nombre, cantidadA, cantidadM, unidad_medida, "
                + "CASE WHEN cantidadA <= cantidadM THEN 'REPONER' ELSE 'OK' END AS estado "
                + "FROM ingredientes "
                + "ORDER BY (cantidadA <= cantidadM) DESC, nombre";

        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            ResultSet rs = st.executeQuery();

            while (rs.next()) {
                Object[] fila = {
                    rs.getString(1),
                    rs.getDouble(2),
                    rs.getDouble(3),
                    rs.getString(4),
                    rs.getString(5)
                };
                modelo.addRow(fila);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }

