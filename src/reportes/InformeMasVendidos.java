    private void cargarMasVendidos() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("Plato");
        modelo.addColumn("Total vendido");
        tblMasVendidos.setModel(modelo);

        String sql = "SELECT pl.nombre, SUM(dp.cantidad) AS total "
                + "FROM detalle_pedido dp "
                + "JOIN pedidos p ON dp.id_pedido = p.id_pedido "
                + "JOIN platos pl ON dp.id_plato = pl.id_plato "
                + "WHERE DATE(p.fecha) BETWEEN ? AND ? "
                + "GROUP BY pl.id_plato, pl.nombre "
                + "ORDER BY total DESC";

        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            st.setString(1, txtDesde.getText());
            st.setString(2, txtHasta.getText());
            ResultSet rs = st.executeQuery();

            while (rs.next()) {
                Object[] fila = {
                    rs.getString(1),
                    rs.getInt(2)
                };
                modelo.addRow(fila);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }

