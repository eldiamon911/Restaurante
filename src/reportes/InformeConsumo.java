    private void cargarConsumo() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("Ingrediente");
        modelo.addColumn("Unidad");
        modelo.addColumn("Total consumido");
        tblConsumo.setModel(modelo);

        String sql = "SELECT i.nombre, i.unidad_medida, "
                + "SUM(ri.cantidad_utilizada * dp.cantidad) AS total "
                + "FROM detalle_pedido dp "
                + "JOIN receta_ingredientes ri ON dp.id_plato = ri.id_plato "
                + "JOIN ingredientes i ON ri.id_ingrediente = i.id_ingrediente "
                + "GROUP BY i.id_ingrediente, i.nombre, i.unidad_medida "
                + "ORDER BY total DESC";

        try {
            Connection con = Conexion.conectar();
            PreparedStatement st = con.prepareStatement(sql);
            ResultSet rs = st.executeQuery();

            while (rs.next()) {
                Object[] fila = {
                    rs.getString(1),
                    rs.getString(2),
                    rs.getDouble(3)
                };
                modelo.addRow(fila);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }

